/** Build an SVG string for `name`. Unknown names throw so typos surface early. */
export function icon(name: string): string {
  const body = PATHS[name];
  if (!body) throw new Error(`unknown icon: ${name}`);
  return (
    '<svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.75" ' +
    `stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${body}</svg>`
  );
}

/** Replace `el`'s contents with the named SVG (static markup, no user input). */
export function setIcon(el: Element, name: string): void {
  setHTML(el, icon(name));
}

/** Swap the contents of every `[data-icon]` element for its named SVG on startup. */
export function hydrateIcons(root: ParentNode = document): void {
  for (const el of root.querySelectorAll<HTMLElement>("[data-icon]")) {
    setIcon(el, el.dataset.icon as string);
  }
}
